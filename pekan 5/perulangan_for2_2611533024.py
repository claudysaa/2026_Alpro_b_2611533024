# Buat program untuk perulangan for dalam python
# Nama variabel ditambah 4 digit nim terakhir contoh: ulang _3024
# Program ini menggunakan fungis input()

ulang_3024 = int(input("Masukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_3024 - 1)
for i_3024 in range(ulang_3024):
    print(i_3024, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_3024)
for i_3024 in range(1, ulang_3024 + 1):
    print(i_3024, end=" ")