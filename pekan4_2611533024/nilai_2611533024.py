nilai_3024 = int(input("Input nilai angka: "))

if nilai_3024 >= 81:
    print("A")
elif nilai_3024 >= 70:
    print("B")
elif nilai_3024 >= 60:
    print("C")
elif nilai_3024 >= 50:
    print("D")
else:
    print("E")